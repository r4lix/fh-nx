#!/usr/bin/env python3
"""Emit host/src/gl_consts.inc: the WebGL constant table (name -> value) from GLES2/gl2.h,
plus the WebGL-only pixel-store constants GLES2 lacks.   gen_gl_consts.py <gl2.h> <out>"""
import re, sys

hdr, out = sys.argv[1], sys.argv[2]
seen = {}
for line in open(hdr, encoding="utf-8", errors="replace"):
    m = re.match(r"#define\s+GL_([A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+|\d+)\b", line)
    if m and m.group(1) not in seen:
        seen[m.group(1)] = m.group(2)
seen.pop("VERSION_ES_CL_1_0", None)
extra = {"UNPACK_FLIP_Y_WEBGL": "0x9240", "UNPACK_PREMULTIPLY_ALPHA_WEBGL": "0x9241",
         "CONTEXT_LOST_WEBGL": "0x9242", "UNPACK_COLORSPACE_CONVERSION_WEBGL": "0x9243",
         "BROWSER_DEFAULT_WEBGL": "0x9244"}
seen.update(extra)
with open(out, "w") as f:
    f.write("/* generated by tools/gen_gl_consts.py from gl2.h: do not edit */\n")
    for k, v in seen.items():
        f.write(f'    {{"{k}", {v}}},\n')
print(len(seen), "constants ->", out)
